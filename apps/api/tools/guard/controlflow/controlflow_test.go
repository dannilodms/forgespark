const nestingMessage = "a second level of nesting: move the inner block into a function of its own (Control flow in CODING_STANDARDS.md)"

// Each case is a function whose third line opens a block inside the block
// of its second line.
func TestASecondLevelOfNestingIsRejected(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"an if in an if": `
	if first {
		if second {
			call()
		}
	}`,
		"an if in a range loop": `
	for range numbers {
		if first {
			call()
		}
	}`,
		"an if in a three-part loop": `
	for index := 0; index < 3; index++ {
		if first {
			call()
		}
	}`,
		"a loop in a loop": `
	for range numbers {
		for range numbers {
			call()
		}
	}`,
		"an if in a switch": `
	switch {
	case first:
		if second {
			call()
		}
	}`,
		"an if in a type switch": `
	switch value.(type) {
	case int:
		if second {
			call()
		}
	}`,
		"an if in a select": `
	select {
	case <-done:
		if second {
			call()
		}
	}`,
		"a select in a loop": `
	for {
		select {
		case <-done:
		}
	}`,
		"a switch in an if": `
	if first {
		switch {
		case second:
		}
	}`,
		"a function literal that nests": `
	go func() {
		for range numbers {
			if first {
				call()
			}
		}
	}()`,
	}
	for name, body := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			root := guardtest.Tree(t, map[string]string{
				"cmd/api/nested.go": "package main\n\nfunc nested(first, second bool, numbers []int, value any, done chan bool) {" + body + "\n}\n",
			})

			findings, err := controlflow.Check(root)

			require.NoError(t, err)
			require.Len(t, findings, 1)
			assert.Equal(t, nestingMessage, findings[0].Message)
			assert.Equal(t, "cmd/api/nested.go", findings[0].File)
		})
	}
}

func TestTheSecondLevelIsReportedWhereItOpens(t *testing.T) {
	t.Parallel()
	root := guardtest.Tree(t, map[string]string{
		"cmd/api/nested.go": `package main

func nested(numbers []int) int {
	count := 0
	for _, number := range numbers {
		if number > 0 {
			count++
		}
	}
	return count
}
`,
	})

	findings, err := controlflow.Check(root)

	require.NoError(t, err)
	assert.Equal(t, []report.Finding{{File: "cmd/api/nested.go", Line: 6, Message: nestingMessage}}, findings)
}

// Each case is the body of a function that holds one level of nesting.
func TestOneLevelOfNestingPasses(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"blocks one after the other": `
	if first {
		call()
	}
	for range numbers {
		call()
	}
	switch {
	case second:
		call()
	}`,
		"a function literal in a block starts again": `
	for range numbers {
		go func() {
			if first {
				call()
			}
		}()
	}`,
		"a function literal in a condition": `
	if func() bool { return first }() {
		call()
	}`,
		"a plain block": `
	{
		if first {
			call()
		}
	}`,
	}
	for name, body := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			root := guardtest.Tree(t, map[string]string{
				"cmd/api/flat.go": "package main\n\nfunc flat(first, second bool, numbers []int) {" + body + "\n}\n",
			})

			findings, err := controlflow.Check(root)

			require.NoError(t, err)
			assert.Empty(t, findings)
		})
	}
}

func TestAnElseIfIsRejectedOnEachBranch(t *testing.T) {
	t.Parallel()
	root := guardtest.Tree(t, map[string]string{
		"cmd/api/sign.go": `package main

func sign(number int) string {
	if number < 0 {
		return "negative"
	} else if number == 0 {
		return "zero"
	} else {
		return "positive"
	}
}
`,
	})

	findings, err := controlflow.Check(root)

	require.NoError(t, err)
	require.Len(t, findings, 2)
	assert.Equal(t, 6, findings[0].Line)
	assert.Equal(t, 8, findings[1].Line)
}

func TestCodeWithNoElsePasses(t *testing.T) {
	t.Parallel()
	root := guardtest.Tree(t, map[string]string{
		"cmd/api/sign.go": `package main

func sign(number int) string {
	if number < 0 {
		return "negative"
	}
	return "positive"
}
`,
	})

	findings, err := controlflow.Check(root)

	require.NoError(t, err)
	assert.Empty(t, findings)
}

func TestGeneratedCodeAndFixturesAreNotJudged(t *testing.T) {
	t.Parallel()
	withElse := `
func sign(number int) string {
	if number < 0 {
		return "negative"
	} else {
		return "positive"
	}
}
`
	root := guardtest.Tree(t, map[string]string{
		"internal/files/adapters/postgres/queries.sql.go": "// Code generated by sqlc. DO NOT EDIT.\n\npackage postgres\n" + withElse,
		"tools/guard/testdata/sign.go":                    "package testdata\n" + withElse,
	})

	findings, err := controlflow.Check(root)

	require.NoError(t, err)
	assert.Empty(t, findings)
}

func TestAFileThatDoesNotParseIsAnError(t *testing.T) {
	t.Parallel()
	root := guardtest.Tree(t, map[string]string{"cmd/api/broken.go": "package main\n\nfunc {"})

	_, err := controlflow.Check(root)

	require.ErrorContains(t, err, "broken.go")
}

func TestAnElseIsRejected(t *testing.T) {
	t.Parallel()
	root := guardtest.Tree(t, map[string]string{
		"internal/platform/clock/clock.go": `package clock

func Sign(number int) string {
	if number < 0 {
		return "negative"
	} else {
		return "positive"
	}
}
`,
	})

	findings, err := controlflow.Check(root)

	require.NoError(t, err)
	assert.Equal(t, []report.Finding{{
		File:    "internal/platform/clock/clock.go",
		Line:    6,
		Message: "else: handle the exceptional case first and return (Control flow in CODING_STANDARDS.md)",
	}}, findings)
}
