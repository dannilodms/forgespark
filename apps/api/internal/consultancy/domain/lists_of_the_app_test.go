// listsOfTheApp is the file the app reads the countries, the currencies and
// the time zones from, so that it offers exactly what the backend accepts and
// no list is typed twice. The countries are the ones of the kernel, which the
// consultancy and its users both have; the currencies and the time zones are
// the consultancy's own. The test runs in the directory of its package: the
// directory of the app is four up.
const listsOfTheApp = "../../../../web/src/shared/places/lists.gen.ts"

// writeLists makes the test below write the file instead of comparing it:
// `task api:lists` passes it.
var writeLists = flag.Bool("write-lists", false, "write the lists the backend accepts to "+listsOfTheApp)

func TestTheAppOffersTheListsTheBackendAccepts(t *testing.T) {
	generated := listsInTypeScript()
	if *writeLists {
		require.NoError(t, os.WriteFile(listsOfTheApp, []byte(generated), 0o644))
		return
	}

	committed, err := os.ReadFile(listsOfTheApp)

	require.NoError(t, err, "the app has no lists: run `task api:lists` and commit the file")
	// A thousand lines: the message says what to do instead of showing them.
	require.True(t, generated == string(committed),
		"apps/web/src/shared/places/lists.gen.ts is not what the lists of the backend generate: run `task api:lists` and commit the file")
}

// listsInTypeScript writes the three lists as constants of TypeScript, each
// value a literal, so that the app can name the type of a code the backend
// accepts.
func listsInTypeScript() string {
	var text strings.Builder
	text.WriteString("// Code generated by `task api:lists` from the lists of apps/api/internal/kernel and apps/api/internal/consultancy/domain. DO NOT EDIT.\n")
	writeList(&text, "countries", "The countries the API accepts, by their ISO 3166-1 alpha-2 code: `countries` in `kernel/countries.go`.", kernel.Countries())
	writeList(&text, "currencies", "The currencies the API accepts, by their ISO 4217 code: `currencies` in `consultancy/domain/currencies.go`.", currencies)
	writeList(&text, "timeZones", "The time zones the API accepts, by their name in the IANA time zone database: `timeZones` in `consultancy/domain/time_zones.go`.", timeZones)
	return text.String()
}

func writeList(text *strings.Builder, name, doc string, values []string) {
	fmt.Fprintf(text, "\n/** %s */\nexport const %s = [\n", doc, name)
	for _, value := range values {
		fmt.Fprintf(text, "  %q,\n", value)
	}
	text.WriteString("] as const\n")
}
